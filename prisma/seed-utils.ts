/**
 * Транслитерирует кириллическую строку в латиницу.
 */
export function transliterate(word: string): string {
	const map: Record<string, string> = {
		'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
		'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
		'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
		'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch',
		'ы': 'y', 'э': 'e', 'ю': 'yu', 'я': 'ya',
		'А': 'a', 'Б': 'b', 'В': 'v', 'Г': 'g', 'Д': 'd', 'Е': 'e', 'Ё': 'e',
		'Ж': 'zh', 'З': 'z', 'И': 'i', 'Й': 'y', 'К': 'k', 'Л': 'l', 'М': 'm',
		'Н': 'n', 'О': 'o', 'П': 'p', 'Р': 'r', 'С': 's', 'Т': 't', 'У': 'u',
		'Ф': 'f', 'Х': 'kh', 'Ц': 'ts', 'Ч': 'ch', 'Ш': 'sh', 'Щ': 'shch',
		'Ы': 'y', 'Э': 'e', 'Ю': 'yu', 'Я': 'ya'
	};

	return word.split('').map(char => map[char] || char).join('');
}

/**
 * Создаёт slug из строки на кириллице.
 * Транслитерирует, приводит к нижнему регистру, заменяет небуквенные символы дефисами.
 */
export function slugify(name: string): string {
	return transliterate(name)
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')  // замена всех символов, кроме букв и цифр, на дефис
		.replace(/^-|-$/g, '');        // удаление дефисов в начале и конце
}